spec = importlib.util.spec_from_file_location('shell_alias_base', Path(__file__).with_name('aliases.py'))
base = importlib.util.module_from_spec(spec)
spec.loader.exec_module(base)
MAGIC = b'MBT-ZSH-ALIASES-2\n'
MAX_FILES, MAX_DEPTH, MAX_TOTAL = 32, 8, 262144
STARTUP = ('.zshenv', '.zprofile', '.zshrc', '.zlogin')
MANAGED = re.compile(r'(?im)^\s*#.*(?:managed by|generated by|chezmoi|yadm|gnu stow)')


def portable(path):
    return (isinstance(path, str) and len(path) <= 512 and
            all(re.fullmatch(r'[A-Za-z0-9_. -]{1,128}', part) and part == part.strip() and part not in ('.', '..', '.git')
                for part in path.split('/')) and not base.SENSITIVE.search(path))


def reference(word, home):
    """An explicit path inside this HOME; no cwd/PATH search or expansion."""
    word = word.strip()
    if len(word) >= 2 and word[0] == word[-1] and word[0] in "'\"":
        quote, word = word[0], word[1:-1]
        if word.startswith('~') or (quote == "'" and '$' in word):
            return None
    elif any(char.isspace() for char in word):
        return None  # Multiple source arguments are not one quoted path.
    for prefix in ('${HOME}/', '$HOME/', '~/', home + '/'):
        if word.startswith(prefix):
            value = word[len(prefix):]
            return value if portable(value) else None
    # An absolute path must start with this exact HOME boundary. Never rewrite
    # another user's path or modify the original source statement.
    return None


@contextmanager
def parent(home, path, *, read_only=False):
    if not portable(path):
        raise base.Invalid('unsafe_source_path')
    with base.home_directory(home) as (root, home_check):
        fd, opened, links = root, [], []
        try:
            for part in path.split('/')[:-1]:
                child = os.open(part, os.O_RDONLY | os.O_DIRECTORY | os.O_NOFOLLOW, dir_fd=fd)
                opened.append(child)
                info = os.fstat(child)
                if info.st_uid != os.getuid() or info.st_mode & 0o022 or info.st_flags:
                    raise base.Invalid('unsafe_source_directory')
                base.acl_safe(child)
                links.append((fd, part, child, base.stamp(info)[:6]))
                fd = child
            def recheck():
                home_check()
                for owner, part, child, expected in links:
                    if (base.stamp(os.fstat(child))[:6] != expected or
                            base.stamp(os.stat(part, dir_fd=owner, follow_symlinks=False))[:6] != expected):
                        raise base.Invalid('target_changed')
                    base.acl_safe(child)
                management = []
                for depth, directory in enumerate((root, *opened)):
                    for marker in ('.git', '.chezmoiroot'):
                        try:
                            info = os.stat(marker, dir_fd=directory, follow_symlinks=False)
                        except FileNotFoundError:
                            continue
                        if not read_only:
                            raise base.Invalid('external_owner')
                        # Marker identity matters; unrelated Git/manager state
                        # inside that directory is neither read nor qualified.
                        management.append((depth, marker, base.stamp(info)[:6]))
                return (tuple(base.stamp(os.fstat(directory))[:6] for directory in (root, *opened)),
                        tuple(management))
            initial = recheck()
            def checked():
                current = recheck()
                if current != initial:
                    raise base.Invalid('target_changed')
                return current
            yield fd, path.split('/')[-1], checked
        finally:
            for child in reversed(opened):
                os.close(child)


def file_state(home, path, ignore_pending=(), *, limit=base.MAX_BYTES):
    with parent(home, path, read_only=True) as (directory, name, recheck):
        if any(entry.startswith('.macseed-shell-pending-') and (str(Path(path).parent), entry) not in ignore_pending
               for entry in os.listdir(directory)):
            raise base.Invalid('publication_uncertain')
        try:
            os.stat(name + '.zwc', dir_fd=directory, follow_symlinks=False)
        except FileNotFoundError:
            pass
        else:
            raise base.Invalid('compiled_source')
        try:
            before = os.stat(name, dir_fd=directory, follow_symlinks=False)
            raw = base.read_file(name, directory, limit=limit)
        except FileNotFoundError:
            recheck()
            return None, None
        info = os.stat(name, dir_fd=directory, follow_symlinks=False)
        if base.stamp(before) != base.stamp(info):
            raise base.Invalid('target_changed')
        return raw, (base.stamp(info), recheck())


def top_level(raw, *, typed=False):
    """Return known unconditional outer statements; retain rejected scope."""
    rows, partial = base.classify(raw, extended=True, typed=typed)
    eligible = {row['statement']: row for row in rows}
    commands, blocks, terminated = [], [], False
    for statement in base.statements(raw.decode('utf-8')):
        first = statement.split(None, 1)[0]
        if first in ('if', 'for', 'while', 'until'):
            blocks.append('fi' if first == 'if' else 'done')
        elif first in ('fi', 'done'):
            if not blocks or blocks.pop() != first:
                raise base.Invalid('ambiguous_context')
            continue
        if not blocks and not terminated:
            commands.append((statement, eligible.get(statement)))
        if first in ('return', 'exit', 'exec') and not blocks:
            terminated = True
    return commands, len(commands) != len(base.statements(raw.decode('utf-8')))


def roots(home, ignore_pending=()):
    location = os.environ.get('ZDOTDIR') or home
    if location == home:
        prefix = ''
    elif location.startswith(home + '/') and portable(location[len(home) + 1:]):
        prefix = location[len(home) + 1:] + '/'
    else:
        raise base.Invalid('unsupported_startup')
    env_path = prefix + '.zshenv'
    raw, _ = file_state(home, env_path, ignore_pending)
    if raw is not None and re.search(rb'\bZDOTDIR\b', raw):
        commands, _ = top_level(raw)
        assignments = [statement for statement, _ in commands if re.fullmatch(r'(?:export\s+)?ZDOTDIR=.*', statement)]
        if len(assignments) != 1 or len(re.findall(rb'\bZDOTDIR\b', raw)) != 1:
            raise base.Invalid('unsupported_startup')
        value = reference(assignments[0].split('=', 1)[1], home)
        if value is None:
            raise base.Invalid('unsupported_startup')
        prefix = value + '/'
    return [env_path, *(prefix + name for name in STARTUP[1:])]


def observe(home, ignore_pending=()):
    graph = dict(roots=roots(home, ignore_pending), files={}, edges=[], aliases=[], mentions={}, functions=set(), partial=False,
                 writable=True, failed=set(), repeated=set(), removed=set(), startup_uncertain=False)
    total, order = 0, 0
    def visit(path, chain):
        nonlocal total, order
        if path in graph['files']:
            graph['repeated'].add(path)
            graph['partial'], graph['writable'] = True, False
            return
        if len(chain) > MAX_DEPTH or len(graph['files']) >= MAX_FILES:
            graph['partial'], graph['writable'] = True, False
            return
        graph['files'][path] = (None, None)
        try:
            raw, info = file_state(home, path, ignore_pending)
            graph['files'][path] = (raw, info)
            if raw is None:
                return
            total += len(raw)
            if (re.search(rb'\bHOME\s*=|\b(?:RCS|GLOBAL_RCS)\b', raw)
                    or (path != graph['roots'][0] and re.search(rb'\bZDOTDIR\s*=', raw))):
                graph['startup_uncertain'] = True
                raise base.Invalid('unsupported_startup')
            if total > MAX_TOTAL:
                raise base.Invalid('unsupported_startup')
            commands, hidden = top_level(raw)
            if hidden:
                graph['writable'] = False
            graph['functions'].update(name for pair in re.findall(
                r'(?:^|[;\n])\s*(?:function\s+)?(' + base.SOURCE_NAME + r')\s*\(\s*\)|(?:^|[;\n])\s*function\s+(' + base.SOURCE_NAME + r')(?![A-Za-z0-9_.-])',
                raw.decode('utf-8')) for name in pair if name)
            uncertain_location = bool(re.search(rb'\b(?:HOME|ZDOTDIR)\s*=', raw)) and path != graph['roots'][0]
            for line in '\n'.join(base.statements(raw.decode('utf-8'))).replace('\\\n', '').splitlines():
                definition = re.search(r'\balias\s+(.*)', line)
                if definition:
                    for name in re.findall(r'(?:^|\s)([A-Za-z0-9_.-]+)\s*=', definition[1]):
                        graph['mentions'][name] = graph['mentions'].get(name, 0) + 1
            if 'source' in graph['functions'] or 'source' in graph['mentions']:
                graph['startup_uncertain'] = True
                raise base.Invalid('ambiguous_source_command')
            for statement, _ in commands:
                if re.fullmatch(r'unalias\s+(?:' + base.SOURCE_NAME + r')(?:\s+' + base.SOURCE_NAME + r')*', statement):
                    graph['removed'].update(statement.split()[1:])
            for statement, alias in commands:
                if alias:
                    order += 1
                    graph['aliases'].append(dict(alias, source=path, chain=chain, order=order))
                    continue
                included = re.fullmatch(r'(?:source|\.)\s+(.+)', statement)
                destination = reference(included[1], home) if included else None
                literal_home = included and included[1].strip().strip('"\'').startswith(home + '/')
                if destination and (not uncertain_location or literal_home):
                    graph['edges'].append((path, destination))
                    visit(destination, [*chain, destination])
                elif re.fullmatch(r'(?:export\s+)?ZDOTDIR=.*', statement) and path == graph['roots'][0]:
                    continue
                else:
                    # Capture can retain independent declarations. This does not
                    # qualify a write or authorize guessed overrides.
                    graph['writable'] = False
                    if re.search(r'\b(?:eval|source|\.)\s|\b(?:HOME|ZDOTDIR)\s*=|\$\(|`', statement):
                        uncertain_location = True
        except (OSError, ValueError) as exc:
            if str(exc) == 'ambiguous_alias_command':
                graph['startup_uncertain'] = True
            graph['partial'], graph['writable'] = True, False
            graph['failed'].add(path)
    for path in graph['roots']:
        visit(path, [path])
    if graph['startup_uncertain']:
        raise base.Invalid('unsupported_startup')
    for path, previous in graph['files'].items():
        if path in graph['failed']:
            continue
        try:
            if file_state(home, path, ignore_pending) != previous:
                raise base.Invalid('target_changed')
        except (OSError, ValueError):
            graph['failed'].add(path)
            graph['writable'] = False
    all_names = set(graph['mentions'])
    graph['aliases'] = [row for row in graph['aliases'] if graph['mentions'].get(row['name']) == 1
                        and row['name'] not in graph['removed']
                        and not any(path in graph['repeated'] for path in row['chain'])
                        and not any(path in graph['failed'] for path in row['chain'])
                        and base.declaration(row['statement'], extended=True)[2] not in (all_names | graph['functions'])]
    if len(graph['aliases']) > base.MAX_ITEMS:
        raise base.Invalid('unsupported_source')
    # A subset of declarations cannot claim complete shell configuration coverage.
    graph['partial'] = True
    return graph


def encode(value):
    return MAGIC + (json.dumps(value, ensure_ascii=True, separators=(',', ':')) + '\n').encode()


def capture(home):
    graph = observe(home)
    if not graph['aliases']:
        raise base.Invalid('no_supported_aliases')
    value = dict(version=2, coverage='partial', roots=graph['roots'], aliases=graph['aliases'])
    return snapshot(encode(value))


def snapshot(raw, *, allow_empty=False):
    def unique(pairs):
        result = {}
        for key, value in pairs:
            if key in result:
                raise base.Invalid('invalid_snapshot')
            result[key] = value
        return result
    if not raw.startswith(MAGIC) or len(raw) > base.MAX_BYTES:
        raise base.Invalid('invalid_snapshot')
    value = json.loads(raw[len(MAGIC):], object_pairs_hook=unique)
    if (not isinstance(value, dict) or set(value) != {'version', 'coverage', 'roots', 'aliases'}
            or type(value['version']) is not int or value['version'] != 2 or value['coverage'] != 'partial'
            or not isinstance(value['roots'], list) or len(value['roots']) != 4
            or any(not portable(p) or p.split('/')[-1] != name for p, name in zip(value['roots'], STARTUP))
            or len({str(Path(p).parent) for p in value['roots'][1:]}) != 1
            or not isinstance(value['aliases'], list) or not (0 if allow_empty else 1) <= len(value['aliases']) <= base.MAX_ITEMS):
        raise base.Invalid('invalid_snapshot')
    previous, names = 0, set()
    for row in value['aliases']:
        if (not isinstance(row, dict) or set(row) != {'name', 'statement', 'source', 'chain', 'order'}
                or not isinstance(row['name'], str) or not isinstance(row['statement'], str)
                or not portable(row['source']) or not isinstance(row['chain'], list)
                or not 1 <= len(row['chain']) <= MAX_DEPTH or any(not portable(p) for p in row['chain'])
                or len(set(row['chain'])) != len(row['chain']) or row['chain'][0] not in value['roots']
                or row['chain'][-1] != row['source'] or type(row['order']) is not int or not previous < row['order'] <= 8192):
            raise base.Invalid('invalid_snapshot')
        parsed = base.declaration(row['statement'], extended=True)
        if (parsed is None or parsed[0]['name'] != row['name'] or row['name'] in names
                or base.statements(row['statement']) != [row['statement']]):
            raise base.Invalid('invalid_snapshot')
        names.add(row['name']); previous = row['order']
    if any(base.declaration(row['statement'], extended=True)[2] in names for row in value['aliases']):
        raise base.Invalid('invalid_snapshot')
    if len(set(value['roots']).union(*(row['chain'] for row in value['aliases']))) > MAX_FILES:
        raise base.Invalid('invalid_snapshot')
    return value


def evidence(value, home, ignore_pending=()):
    try:
        graph = observe(home, ignore_pending)
        state = {path: (hashlib.sha256(raw).hexdigest() if raw is not None else None, info)
                 for path, (raw, info) in graph['files'].items()}
        # Also bind destinations whose dependency is currently missing.
        for row in value['aliases']:
            for path in row['chain']:
                if path not in state:
                    try:
                        raw, info = file_state(home, path, ignore_pending)
                        state[path] = (hashlib.sha256(raw).hexdigest() if raw is not None else None, info)
                    except (OSError, ValueError):
                        state[path] = 'unsafe'
        payload = dict(files=state, roots=graph['roots'], failed=sorted(graph['failed']),
                       dependencies=dependency_states(value, home))
        return hashlib.sha256(json.dumps(payload, sort_keys=True).encode()).hexdigest()
    except (OSError, ValueError):
        return hashlib.sha256(b'unsafe-source-observation').hexdigest()


def dependencies(value):
    """References inside alias bodies are prerequisites, never startup edges."""
    result = {}
    for row in value['aliases']:
        parsed = base.declaration(row['statement'], extended=True)
        words = shlex.split(parsed[1])
        source = words[0] in ('source', '.')
        tokens = shlex.split(parsed[1], posix=False)
        if source and (len(words) != 2 or (tokens[1][:1] in "'\"" and tokens[1][1:].startswith('~'))):
            continue  # Legacy literal operands are not proven HOME references.
        path = base.home_reference(words[1] if source else words[0])
        if path is not None:
            result[path] = result.get(path, False) or not source
    if value.get('version') == 4:
        result.update((script['path'], True) for script in value.get('scripts', []))
    if value.get('version') == 5:
        for script in value.get('scripts', []):
            result.setdefault(script['path'], False)
    return result


def dependency_states(value, home, script_paths=(), *, transfer=False):
    """Observe metadata only. Never read, copy or execute referenced scripts."""
    result = {}
    paths = dependencies(value)
    for path in script_paths:
        paths.setdefault(path, not transfer)
    for path, executable in paths.items():
        if transfer:
            executable = False  # File inclusion never proves direct invocation.
        try:
            with parent(home, path, read_only=True) as (directory, name, recheck):
                if not executable:
                    try:
                        os.stat(name + '.zwc', dir_fd=directory, follow_symlinks=False)
                    except FileNotFoundError:
                        pass
                    else:
                        raise base.Invalid('compiled_dependency')
                fd = os.open(name, os.O_RDONLY | os.O_NOFOLLOW | os.O_NONBLOCK, dir_fd=directory)
                try:
                    info = os.fstat(fd)
                    if (not stat.S_ISREG(info.st_mode) or info.st_uid != os.getuid() or info.st_nlink != 1
                            or info.st_mode & 0o022 or not info.st_mode & 0o400
                            or info.st_flags & ~base.USER_READ_FLAGS or (executable and not info.st_mode & 0o100)):
                        raise base.Invalid('unsafe_dependency')
                    base.acl_safe(fd)
                    parents = recheck()
                    if base.stamp(info) != base.stamp(os.stat(name, dir_fd=directory, follow_symlinks=False)):
                        raise base.Invalid('target_changed')
                    result[path] = ('ready', (base.stamp(info), parents))
                finally:
                    os.close(fd)
        except FileNotFoundError:
            result[path] = ('missing', None)
        except (OSError, ValueError):
            result[path] = ('unverified', None)
    return result


def assess(value, home):
    try:
        graph = observe(home)
    except (OSError, ValueError):
        return [(row, 'unverified', 'preserve') for row in value['aliases']]
    current = {row['name']: row for row in graph['aliases']}
    result = []
    for row in value['aliases']:
        found = current.get(row['name'])
        chain = row['chain']
        connected = (value['roots'] == graph['roots'] and chain[0] in graph['roots']
                     and all((a, b) in graph['edges'] for a, b in zip(chain, chain[1:])))
        safe = connected and not any(path in graph['failed'] or path in graph['repeated'] for path in chain)
        if found and safe and found['source'] == row['source'] and found['chain'] == chain:
            state = 'matching' if base.declaration(found['statement'], extended=True)[1] == base.declaration(row['statement'], extended=True)[1] else 'differing'
            result.append((row, state, 'preserve'))
        elif not safe or graph['mentions'].get(row['name'], 0):
            result.append((row, 'unverified', 'preserve'))
        else:
            policy = 'preserve'
            if graph['writable']:
                try:
                    with parent(home, row['source']) as (directory, name, recheck):
                        raw, _ = file_state(home, row['source'])
                        if raw is None:
                            policy = 'create'
                        else:
                            mutable_file(directory, name)
                            policy = 'add'
                        swap_supported(directory)
                        recheck()
                except (OSError, ValueError):
                    pass
            result.append((row, 'missing', policy))
    selected_sources = {row['source'] for row in value['aliases']}
    missing_dependencies = {destination for _, destination in graph['edges']
                            if graph['files'].get(destination, (None, None))[0] is None} - selected_sources
    blocked = bool(missing_dependencies) or any(state != 'matching' and policy == 'preserve' for _, state, policy in result)
    pending_sources = {row['source'] for row, state, policy in result if policy == 'create'}
    references = dependencies(value)
    # An inert reload alias may refer to the source file being created. Every
    # other prerequisite must already be qualified; no script installation.
    blocked |= any(state != 'ready' and not (state == 'missing' and path in pending_sources and not references[path])
                   for path, (state, _) in dependency_states(value, home).items())
    for path in selected_sources:
        extra = [row['statement'] for row, state, policy in result if row['source'] == path and policy in ('add', 'create')]
        raw = graph['files'].get(path, (None, None))[0] or b''
        if len(raw) + len(('\n'.join(extra) + '\n').encode()) + 1 > base.MAX_BYTES:
            blocked = True
    return [(row, state, 'preserve' if blocked and policy in ('add', 'create') else policy) for row, state, policy in result]


def native():
    lib = C.CDLL(None, use_errno=True)
    lib.renameatx_np.argtypes = [C.c_int, C.c_char_p, C.c_int, C.c_char_p, C.c_uint]
    lib.renameatx_np.restype = C.c_int
    lib.fgetattrlist.argtypes = [C.c_int, C.c_void_p, C.c_void_p, C.c_size_t, C.c_ulong]
    lib.acl_get_fd_np.argtypes = [C.c_int, C.c_int]
    lib.acl_get_fd_np.restype = C.c_void_p
    lib.acl_get_entry.argtypes = [C.c_void_p, C.c_int, C.POINTER(C.c_void_p)]
    lib.acl_free.argtypes = [C.c_void_p]
    lib.flistxattr.argtypes = [C.c_int, C.c_void_p, C.c_size_t, C.c_int]
    lib.flistxattr.restype = C.c_ssize_t
    lib.fgetxattr.argtypes = [C.c_int, C.c_char_p, C.c_void_p, C.c_size_t, C.c_uint, C.c_int]
    lib.fgetxattr.restype = C.c_ssize_t
    lib.fcopyfile.argtypes = [C.c_int, C.c_int, C.c_void_p, C.c_uint]
    return lib


def swap_supported(fd, *, documents=False):
    class Attributes(C.Structure):
        _fields_ = [('count', C.c_ushort), ('reserved', C.c_ushort), ('common', C.c_uint),
                    ('volume', C.c_uint), ('directory', C.c_uint), ('file', C.c_uint), ('fork', C.c_uint)]
    class Capabilities(C.Structure):
        _fields_ = [('length', C.c_uint), ('capabilities', C.c_uint * 4), ('valid', C.c_uint * 4)]
    attributes, caps = Attributes(5, 0, 0, 0x80020000, 0, 0, 0), Capabilities()
    if (native().fgetattrlist(fd, C.byref(attributes), C.byref(caps), C.sizeof(caps), 0)
            or caps.length != C.sizeof(caps) or caps.valid[1] & caps.capabilities[1] & 0xC0000 != 0xC0000):
        raise base.Invalid('publication_unavailable')
    if documents and not caps.valid[0] & caps.capabilities[0] & 0x80000:
        raise base.Invalid('publication_unavailable')


def document_id(directory, name, expected):
    """Read the tracked document identity without creating or changing it."""
    class Attributes(C.Structure):
        _fields_ = [('count', C.c_ushort), ('reserved', C.c_ushort), ('common', C.c_uint),
                    ('volume', C.c_uint), ('directory', C.c_uint), ('file', C.c_uint), ('fork', C.c_uint)]
    if expected.st_flags != base.USER_READ_FLAGS:
        raise base.Invalid('unsupported_metadata')
    fd = os.open(name, os.O_RDONLY | os.O_NOFOLLOW | os.O_NONBLOCK, dir_fd=directory)
    try:
        attributes, result = Attributes(5, 0, 0x100000, 0, 0, 0, 0), (C.c_uint * 2)()
        if (base.stamp(os.fstat(fd)) != base.stamp(expected)
                or native().fgetattrlist(fd, C.byref(attributes), C.byref(result), C.sizeof(result), 0x20)
                or result[0] != C.sizeof(result) or not result[1]):
            raise base.Invalid('document_identity_unavailable')
        if (base.stamp(os.fstat(fd)) != base.stamp(expected)
                or base.stamp(os.stat(name, dir_fd=directory, follow_symlinks=False)) != base.stamp(expected)):
            raise base.Invalid('target_changed')
        return result[1]
    finally:
        os.close(fd)


def track_staged(fd):
    lib = native()
    lib.fchflags.argtypes = [C.c_int, C.c_uint]
    lib.fchflags.restype = C.c_int
    if os.fstat(fd).st_flags or lib.fchflags(fd, base.USER_READ_FLAGS) or os.fstat(fd).st_flags != base.USER_READ_FLAGS:
        raise base.Invalid('unsupported_metadata')


def rename(a, source, b, destination, flag):
    if native().renameatx_np(a, os.fsencode(source), b, os.fsencode(destination), flag | 0x30):
        raise OSError(C.get_errno(), 'Shell publication failed')


def attributes(fd):
    lib = native(); size = lib.flistxattr(fd, None, 0, 0)
    if not 0 <= size <= 8192:
        raise base.Invalid('unsupported_metadata')
    names = C.create_string_buffer(size)
    if lib.flistxattr(fd, names, size, 0) != size:
        raise base.Invalid('target_changed')
    entries = names.raw.split(b'\0')[:-1] if size else []
    if len(entries) > 32 or (size and not names.raw.endswith(b'\0')):
        raise base.Invalid('unsupported_metadata')
    result = {}
    for name in entries:
        size = lib.fgetxattr(fd, name, None, 0, 0, 0)
        if not name or not 0 <= size <= 32768:
            raise base.Invalid('unsupported_metadata')
        value = C.create_string_buffer(size)
        if lib.fgetxattr(fd, name, value, size, 0, 0) != size:
            raise base.Invalid('target_changed')
        result[name] = value.raw
    return result


def mutable_file(directory, name, *, limit=base.MAX_BYTES, tracked=False, created_content=None):
    before = os.stat(name, dir_fd=directory, follow_symlinks=False)
    raw = base.read_file(name, directory, limit=limit)
    if raw != created_content and MANAGED.search(raw.decode('utf-8', errors='replace')):
        raise base.Invalid('external_owner')
    fd = os.open(name, os.O_RDONLY | os.O_NOFOLLOW | os.O_NONBLOCK, dir_fd=directory)
    try:
        info = os.fstat(fd)
        # Only explicitly qualified v5 source appends may use tracked safe-save.
        # Legacy writers and opaque script files keep the strict flags policy.
        if info.st_flags:
            if not tracked or info.st_flags != base.USER_READ_FLAGS:
                raise base.Invalid('unsupported_metadata')
            swap_supported(directory, documents=True)
            document_id(directory, name, info)
        metadata = attributes(fd)
        lib = native(); acl = lib.acl_get_fd_np(fd, 0x100)
        if acl:
            try:
                entry = C.c_void_p()
                if lib.acl_get_entry(acl, 0, C.byref(entry)) == 0 or C.get_errno() != errno.EINVAL:
                    raise base.Invalid('unsupported_metadata')
            finally:
                lib.acl_free(acl)
        elif C.get_errno() != errno.ENOENT:
            raise base.Invalid('unsupported_metadata')
        if (base.stamp(info) != base.stamp(before)
                or base.stamp(info) != base.stamp(os.stat(name, dir_fd=directory, follow_symlinks=False))):
            raise base.Invalid('target_changed')
        return raw, info, metadata
    finally:
        os.close(fd)


def write_file(directory, name, raw, mode=0o600, gid=None, source=None, prepare=None, *, source_update=False):
    fd = os.open(name, os.O_WRONLY | os.O_CREAT | os.O_EXCL | os.O_NOFOLLOW, 0o600, dir_fd=directory)
    with os.fdopen(fd, 'wb') as stream:
        if gid is not None:
            os.fchown(stream.fileno(), -1, gid)
        os.fchmod(stream.fileno(), mode)
        stream.write(raw); stream.flush()
        copied_metadata = None
        if source is not None:
            owner, filename, observed, metadata = source
            # Provenance is opaque OS-owned metadata on the NEW inode. A copy
            # across application origins may retain its OS-created value. Never
            # parse, set or remove it, or infer trust from it. Legacy copying
            # remains exact; only qualified v5 source updates use this rule.
            created = attributes(stream.fileno())
            copied = dict(metadata)
            if source_update and b'com.apple.provenance' in created:
                copied[b'com.apple.provenance'] = created[b'com.apple.provenance']
            original = os.open(filename, os.O_RDONLY | os.O_NOFOLLOW | os.O_NONBLOCK, dir_fd=owner)
            try:
                if (base.stamp(os.fstat(original)) != base.stamp(observed)
                        or attributes(original) != metadata):
                    raise base.Invalid('target_changed')
                if native().fcopyfile(original, stream.fileno(), None, 4):
                    raise base.Invalid('metadata_copy_failed')
                copied_metadata = attributes(stream.fileno())
                if copied_metadata not in (metadata, copied):
                    raise base.Invalid('metadata_copy_mismatch')
                if (attributes(original) != metadata
                        or base.stamp(os.fstat(original)) != base.stamp(observed)):
                    raise base.Invalid('target_changed')
            finally:
                os.close(original)
        if prepare is not None:
            prepare(stream.fileno())
        os.fsync(stream.fileno())
        fcntl.fcntl(stream.fileno(), 51)
        actual_metadata = attributes(stream.fileno())
        if copied_metadata is not None and actual_metadata != copied_metadata:
            raise base.Invalid('target_changed')
        return actual_metadata


def publish_file(home, path, additions, validate):
    original, _ = file_state(home, path)
    original = original or b''
    suffix = ('\n'.join(row['statement'] for row in additions) + '\n').encode()
    candidate = original + (b'\n' if original and not original.endswith(b'\n') else b'') + suffix
    qualified, _ = base.classify(candidate, extended=True)
    if not all({'name': row['name'], 'statement': row['statement']} in qualified for row in additions):
        raise base.Invalid('candidate_invalid')
    return publish_content(home, path, candidate, validate)


def publish_content(home, path, candidate, validate, mode=0o600, *, limit=base.MAX_BYTES, prepare=None, verify=None, tracked=False, create_only=False):
    # Callers qualify the candidate; this publisher preserves metadata and races.
    with parent(home, path) as (directory, name, recheck):
        try:
            original, old, metadata = mutable_file(directory, name, limit=limit, tracked=tracked)
        except FileNotFoundError:
            original, old, metadata = b'', None, None
        if create_only and old is not None:
            raise base.Invalid('target_changed')
        if len(candidate) > limit or (old is not None and not candidate.startswith(original)):
            raise base.Invalid('candidate_invalid')
        document = document_id(directory, name, old) if old is not None and old.st_flags else None
        if document is not None:
            if prepare is not None or verify is not None:
                raise base.Invalid('unsupported_metadata')
            # Set tracking only on the new staging inode. APFS safe-save swaps
            # document IDs while retaining tracking on both objects. Never clear
            # flags on the source, or repair a failed identity check after publish.
            prepare = track_staged
        swap_supported(directory)
        validate(); recheck()
        token = uuid.uuid4().hex
        pending = '.macseed-shell-pending-' + token
        completed = '.macseed-shell-predecessor-' + token
        os.mkdir(pending, 0o700, dir_fd=directory)
        recovery, phase = None, 'staging'
        try:
            recovery = os.open(pending, os.O_RDONLY | os.O_DIRECTORY | os.O_NOFOLLOW, dir_fd=directory)
            recovery_identity = base.stamp(os.fstat(recovery))[:6]
            def recovery_check():
                if base.stamp(os.stat(pending, dir_fd=directory, follow_symlinks=False))[:6] != recovery_identity:
                    raise base.Invalid('publication_uncertain')
            if old is not None:
                write_file(recovery, 'observed', original, stat.S_IMODE(old.st_mode), old.st_gid,
                           (directory, name, old, metadata), source_update=tracked)
            staged_metadata = write_file(recovery, 'swap', candidate, stat.S_IMODE(old.st_mode) if old else mode,
                       old.st_gid if old else None, (directory, name, old, metadata) if old else None, prepare,
                       source_update=tracked)
            staged = os.stat('swap', dir_fd=recovery, follow_symlinks=False)
            staged_document = document_id(recovery, 'swap', staged) if document is not None else None
            if document is not None and staged_document == document:
                raise base.Invalid('document_identity_unavailable')
            os.fsync(recovery); os.fsync(directory); recheck()
            if old is not None:
                latest, observed, current_metadata = mutable_file(directory, name, limit=limit, tracked=tracked)
                if (latest != original or base.stamp(observed) != base.stamp(old) or current_metadata != metadata
                        or (document is not None and document_id(directory, name, observed) != document)):
                    raise base.Invalid('target_changed')
            validate(((str(Path(path).parent), pending),))
            recovery_check()
            if verify is not None or old is not None:
                descriptor = os.open('swap', os.O_RDONLY | os.O_NOFOLLOW | os.O_NONBLOCK, dir_fd=recovery)
                try:
                    if verify is not None:
                        verify(descriptor)
                    if old is not None and attributes(descriptor) != staged_metadata:
                        raise base.Invalid('target_changed')
                    if base.stamp(os.fstat(descriptor)) != base.stamp(staged):
                        raise base.Invalid('target_changed')
                finally:
                    os.close(descriptor)
            # Swap preserves a last-gap competing writer as the displaced file.
            # Never unlink or roll back either side on uncertain publication.
            phase = 'exchange'
            rename(recovery, 'swap', directory, name, 2 if old else 4)
            phase = 'verification'
            # In a no-clobber Script creation the exact staged bytes may carry
            # source-manager comments. Directory ownership and inode checks still apply.
            actual, published, published_metadata = mutable_file(directory, name, limit=limit, tracked=tracked,
                created_content=candidate if create_only else None)
            if (actual != candidate or base.stamp(published)[:6] != base.stamp(staged)[:6]
                    or (old is not None and published_metadata != staged_metadata)):
                raise base.Invalid('publication_uncertain')
            if document is not None and document_id(directory, name, published) != document:
                raise base.Invalid('publication_uncertain')
            if verify is not None:
                descriptor = os.open(name, os.O_RDONLY | os.O_NOFOLLOW | os.O_NONBLOCK, dir_fd=directory)
                try:
                    verify(descriptor)
                    if (base.stamp(os.fstat(descriptor)) != base.stamp(published)
                            or base.stamp(os.stat(name, dir_fd=directory, follow_symlinks=False)) != base.stamp(published)):
                        raise base.Invalid('publication_uncertain')
                finally:
                    os.close(descriptor)
            if old is not None:
                displaced, previous, previous_metadata = mutable_file(recovery, 'swap', limit=limit, tracked=tracked)
                if (displaced != original or base.stamp(previous)[:8] != base.stamp(old)[:8]
                        or previous.st_mtime_ns != old.st_mtime_ns or previous_metadata != metadata
                        or (document is not None and document_id(recovery, 'swap', previous) != staged_document)):
                    raise base.Invalid('publication_uncertain')
            recheck(); os.fsync(recovery); os.fsync(directory)
            recovery_check()
            rename(directory, pending, directory, completed, 4)
        except BaseException as exc:
            failure = base.PublicationUncertain('publication_uncertain')
            failure.phase = phase
            raise failure from exc
        finally:
            if recovery is not None:
                os.close(recovery)


def publish(value, home, expected=None):
    wanted = evidence(value, home)
    if expected is not None and expected != wanted:
        raise base.Invalid('target_changed')
    baseline = observe(home)
    baseline_dependencies = dependency_states(value, home)
    rows = assess(value, home)
    if all(state == 'matching' for _, state, _ in rows):
        return False
    if any(state != 'matching' and policy not in ('add', 'create') for _, state, policy in rows):
        raise base.Invalid('target_conflict')
    grouped = {}
    for row, state, policy in rows:
        if state != 'matching':
            grouped.setdefault(row['source'], []).append(row)
    changed = False
    try:
        for path, additions in grouped.items():
            def validate(ignore_pending=()):
                if evidence(value, home, ignore_pending) != wanted:
                    raise base.Invalid('target_changed')
            validate()
            publish_file(home, path, additions, validate)
            changed = True
            current = observe(home)
            current_dependencies = dependency_states(value, home)
            if (current['roots'] != baseline['roots'] or current['edges'] != baseline['edges']
                    or {key: state for key, state in current_dependencies.items() if key != path}
                    != {key: state for key, state in baseline_dependencies.items() if key != path}
                    or {key: state for key, state in current['files'].items() if key != path}
                    != {key: state for key, state in baseline['files'].items() if key != path}):
                raise base.PublicationUncertain('source_changed')
            baseline = current
            baseline_dependencies = current_dependencies
            wanted = evidence(value, home)
        if not all(state == 'matching' for _, state, _ in assess(value, home)):
            raise base.PublicationUncertain('verification_failed')
    except (OSError, ValueError) as exc:
        if changed or isinstance(exc, base.PublicationUncertain):
            raise base.PublicationUncertain('publication_uncertain') from exc
        raise
    return changed
